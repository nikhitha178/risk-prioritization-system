
import os
import csv
from collections import defaultdict
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parent.parent

DATA_DIR = Path(
    os.getenv("DATA_DIR", PROJECT_ROOT / "data")
)
EVALUATION_DIR = Path(__file__).resolve().parent


def read_csv(path):
    with open(path, "r", encoding="utf-8") as file:
        return list(csv.DictReader(file))


def calculate_scores(tp, fp, fn):
    precision = tp / (tp + fp) if tp + fp else 0
    recall = tp / (tp + fn) if tp + fn else 0

    f1 = (
        2 * precision * recall / (precision + recall)
        if precision + recall else 0
    )

    return {
        "true_positives": tp,
        "false_positives": fp,
        "false_negatives": fn,
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "f1_score": round(f1, 4),
    }


def main():
    # Read actual risk-engine output and ground truth.
    alerts = read_csv(DATA_DIR / "alerts.csv")
    ground_truth = read_csv(DATA_DIR / "ground_truth.csv")
    rules = read_csv(DATA_DIR / "risk_rules.csv")

    # Map rule IDs to their risk categories.
    rule_lookup = {
        rule["rule_id"]: rule["rule_category"]
        for rule in rules
    }

    # Map planted anomaly types to risk-rule categories.
    issue_mapping = {
        "HIGH_VALUE": "HIGH_VALUE",
        "VELOCITY_SPIKE": "VELOCITY",
        "NEW_DEVICE": "NEW_DEVICE",
        "CIRCULAR_TRANSFER": "CIRCULAR_TRANSFER",
        "DORMANT_REACTIVATION": "DORMANT_REACTIVATION",
    }

    # Expected transaction-rule pairs.
    expected_pairs = set()

    for row in ground_truth:
        category = issue_mapping.get(row["issue_type"])

        if category:
            expected_pairs.add(
                (row["transaction_id"], category)
            )

    # Actual transaction-rule pairs generated by the engine.
    detected_pairs = set()

    for alert in alerts:
        category = rule_lookup.get(alert["rule_id"])

        if category:
            detected_pairs.add(
                (alert["transaction_id"], category)
            )

    # Compare expected and detected pairs.
    true_positive_pairs = expected_pairs & detected_pairs
    false_positive_pairs = detected_pairs - expected_pairs
    false_negative_pairs = expected_pairs - detected_pairs

    # Save detailed comparison results.
    comparison_rows = []

    for transaction_id, category in sorted(true_positive_pairs):
        comparison_rows.append({
            "transaction_id": transaction_id,
            "issue_type": category,
            "result": "TRUE_POSITIVE",
        })

    for transaction_id, category in sorted(false_positive_pairs):
        comparison_rows.append({
            "transaction_id": transaction_id,
            "issue_type": category,
            "result": "FALSE_POSITIVE",
        })

    for transaction_id, category in sorted(false_negative_pairs):
        comparison_rows.append({
            "transaction_id": transaction_id,
            "issue_type": category,
            "result": "FALSE_NEGATIVE",
        })

    comparison_path = EVALUATION_DIR / "detection_results.csv"

    with open(
        comparison_path,
        "w",
        newline="",
        encoding="utf-8",
    ) as file:
        writer = csv.DictWriter(
            file,
            fieldnames=["transaction_id", "issue_type", "result"],
        )
        writer.writeheader()
        writer.writerows(comparison_rows)

    # Overall metrics.
    summaries = [{
        "scope": "OVERALL",
        "category": "ALL",
        **calculate_scores(
            len(true_positive_pairs),
            len(false_positive_pairs),
            len(false_negative_pairs),
        ),
    }]

    # Category-wise metrics.
    categories = sorted(
        set(category for _, category in expected_pairs)
        | set(category for _, category in detected_pairs)
    )

    for category in categories:
        expected = {
            pair for pair in expected_pairs
            if pair[1] == category
        }

        detected = {
            pair for pair in detected_pairs
            if pair[1] == category
        }

        tp = len(expected & detected)
        fp = len(detected - expected)
        fn = len(expected - detected)

        summaries.append({
            "scope": "CATEGORY",
            "category": category,
            **calculate_scores(tp, fp, fn),
        })

    # Save metrics.
    output_path = EVALUATION_DIR / "metrics_summary.csv"

    fieldnames = [
        "scope",
        "category",
        "true_positives",
        "false_positives",
        "false_negatives",
        "precision",
        "recall",
        "f1_score",
    ]

    with open(
        output_path,
        "w",
        newline="",
        encoding="utf-8",
    ) as file:
        writer = csv.DictWriter(file, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(summaries)

    print("\nDETECTION EVALUATION")
    print("=" * 55)
    print(f"Ground-truth anomaly pairs: {len(expected_pairs)}")
    print(f"Detected transaction-rule pairs: {len(detected_pairs)}")
    print(f"Comparison records: {len(comparison_rows)}")

    print("\nRISK DETECTION PERFORMANCE")
    print("=" * 55)

    for summary in summaries:
        print(f"\n{summary['category']}")
        print(f"True positives:  {summary['true_positives']}")
        print(f"False positives: {summary['false_positives']}")
        print(f"False negatives: {summary['false_negatives']}")
        print(f"Precision:       {summary['precision']:.2%}")
        print(f"Recall:          {summary['recall']:.2%}")
        print(f"F1-score:        {summary['f1_score']:.2%}")

    print(f"\nComparison saved: {comparison_path}")
    print(f"Metrics saved: {output_path}")


if __name__ == "__main__":
    main()
